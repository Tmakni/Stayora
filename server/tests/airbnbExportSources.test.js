describe('traçabilité et arbitrage des conflits', () => {
  const permitsAddress = {
    name: 'listing_permits.json',
    data: [{ listingRegistrations: [{
      listingUrl: `https://www.airbnb.com/rooms/${SMALL_ID}`,
      registrations: [{ registrationSubmissions: [{ data: { listing_address: 'Adresse déclarée différente' } }] }],
    }] }],
  };

  it('note le fichier d\'origine de chaque champ', () => {
    const [listing] = parseExportDocuments([listingsDoc([rawListing()])]).listings;
    expect(listing.import_sources.name).toBe('listings.json');
    expect(listing.import_sources.max_guests).toBe('listings.json');
    expect(listing.import_sources.has_wifi).toBe('listings.json');
  });

  it('la source la plus autoritative garde la main, et le désaccord est noté', () => {
    const { listings, conflicts } = parseExportDocuments([
      listingsDoc([rawListing()]), permitsAddress,
    ]);
    expect(listings[0].address).toBe('12 Rue des Ardillères, 33290 Parempuyre, France');
    expect(listings[0].import_sources.address).toBe('listings.json');
    expect(conflicts).toContainEqual({
      listing_id: SMALL_ID,
      field: 'address',
      kept_from: 'listings.json',
      ignored_from: 'listing_permits.json',
    });
  });

  it('ne signale aucun conflit quand les deux sources concordent', () => {
    const same = {
      name: 'listing_permits.json',
      data: [{ listingRegistrations: [{
        listingUrl: `https://www.airbnb.com/rooms/${SMALL_ID}`,
        registrations: [{ registrationSubmissions: [{
          data: { listing_address: '12 Rue des Ardillères, 33290 Parempuyre, France' },
        }] }],
      }] }],
    };
    const { conflicts } = parseExportDocuments([listingsDoc([rawListing()]), same]);
    expect(conflicts).toEqual([]);
  });

  it('une source secondaire comble un vide sans jamais écraser', () => {
    const { listings } = parseExportDocuments([
      listingsDoc([rawListing({ formattedAddress: '', street: '', zipcode: '', city: '', country: '' })]),
      permitsAddress,
    ]);
    expect(listings[0].address).toBe('Adresse déclarée différente');
    expect(listings[0].import_sources.address).toBe('listing_permits.json');
  });
});

