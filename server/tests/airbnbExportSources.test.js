describe('rien n\'est inventé', () => {
  it('ne remplace pas une valeur absente par un zéro', () => {
    const [listing] = parseExportDocuments([listingsDoc([
      rawListing({ bedrooms: null, beds: null, personCapacity: null, bathrooms: null }),
    ])]).listings;
    expect(listing.bedrooms).toBeUndefined();
    expect(listing.beds).toBeUndefined();
    expect(listing.max_guests).toBeUndefined();
    expect(listing.bathrooms).toBeUndefined();
    expect(listing.found.capacity).toBe(false);
  });

  it('ne coche aucun équipement quand la liste est absente', () => {
    const [listing] = parseExportDocuments([listingsDoc([
      rawListing({ amenities: null }),
    ])]).listings;
    expect(Object.keys(listing).filter((k) => k.startsWith('has_'))).toEqual([]);
    expect(listing.found.amenities).toBe(false);
  });

  it('n\'écrit pas d\'instructions que l\'hôte n\'a pas écrites', () => {
    const [listing] = parseExportDocuments([listingsDoc([
      rawListing({ amenities: ['cleaning_before_checkout', 'luggage_dropoff_allowed'] }),
    ])]).listings;
    // Ces deux codes disent qu'une chose est possible, pas comment ni à quelle
    // condition. Les phrases correspondantes auraient été écrites par nous.
    expect(listing.checkout_instructions).toBeUndefined();
    expect(listing.luggage_storage).toBeUndefined();
  });

  it('conserve la valeur exacte des demi-salles de bain', () => {
    const [listing] = parseExportDocuments([listingsDoc([rawListing({ bathrooms: 1.5 })])]).listings;
    // La colonne est entière, mais ce n'est pas elle que Michel cite.
    expect(listing.bathrooms).toBe(2);
    expect(listing.bathrooms_exact).toBe(1.5);
  });

  it('reprend le règlement écrit par l\'hôte plutôt que de le reformuler', () => {
    const [listing] = parseExportDocuments([listingsDoc([rawListing({
      listingDescriptions: [{ name: 'Test', houseRules: 'Pas de musique après 22 h.' }],
    })])]).listings;
    expect(listing.house_rules).toContain('Pas de musique après 22 h.');
  });

  it('ne traduit pas un type de logement absent du menu de la fiche', () => {
    const [listing] = parseExportDocuments([listingsDoc([
      rawListing({ propertyType: 'Yourte mongole' }),
    ])]).listings;
    expect(listing.property_type).toBeUndefined();
  });
});
