describe('reservations.json — séjours à venir', () => {
  it('ne retient que les séjours à venir et calcule la date de départ', () => {
    const { listings } = parseExportDocuments([
      listingsDoc([rawListing()]),
      reservationsDoc([
        { confirmationCode: 'FUTUR1', hostingUrl: `https://www.airbnb.com/rooms/${SMALL_ID}`, startDate: FUTURE, nights: 3, status: 'accepted', numberOfGuests: 2 },
        { confirmationCode: 'PASSE1', hostingUrl: `https://www.airbnb.com/rooms/${SMALL_ID}`, startDate: PAST, nights: 2, status: 'accepted', numberOfGuests: 2 },
      ]),
    ]);

    expect(listings[0].reservations).toHaveLength(1);
    const [stay] = listings[0].reservations;
    expect(stay.confirmation_code).toBe('FUTUR1');
    expect(stay.check_in_date).toBe(FUTURE);

    // Départ = arrivée + nuits. C'est la définition d'une nuitée, pas une
    // estimation : la date de départ n'existe pas telle quelle dans l'export.
    const expected = new Date(`${FUTURE}T00:00:00Z`);
    expected.setUTCDate(expected.getUTCDate() + 3);
    expect(stay.check_out_date).toBe(expected.toISOString().slice(0, 10));
    expect(listings[0].found.reservations).toBe(true);
  });

  it('ne fait entrer aucune donnée du voyageur dans la fiche', () => {
    const { listings } = parseExportDocuments([
      listingsDoc([rawListing()]),
      reservationsDoc([{
        confirmationCode: 'FUTUR2', hostingUrl: `https://www.airbnb.com/rooms/${SMALL_ID}`,
        startDate: FUTURE, nights: 2, status: 'accepted', numberOfGuests: 2,
        message: 'Bonjour, je serai en retard',
        guestProfileUrl: 'https://www.airbnb.com/users/show/999',
        guestVatCountry: 'FR', hostCurrency: 'EUR', guestCheckinTimeFrom: 21,
      }]),
    ]);

    const serialized = JSON.stringify(listings[0]);
    expect(serialized).not.toContain('en retard');
    expect(serialized).not.toContain('users/show/999');
    // `guestCheckinTimeFrom` est l'heure annoncée par CE voyageur : elle ne
    // doit jamais devenir l'heure d'arrivée du logement.
    expect(listings[0].check_in_time).toBeUndefined();
  });

  it('écarte un statut inconnu plutôt que de le traduire au jugé', () => {
    const { listings } = parseExportDocuments([
      listingsDoc([rawListing()]),
      reservationsDoc([
        { confirmationCode: 'X1', hostingUrl: `https://www.airbnb.com/rooms/${SMALL_ID}`, startDate: FUTURE, nights: 1, status: 'wibble' },
      ]),
    ]);
    expect(listings[0].reservations).toEqual([]);
  });

  it('écarte un séjour sans code de confirmation, faute de clé stable', () => {
    const { listings } = parseExportDocuments([
      listingsDoc([rawListing()]),
      reservationsDoc([
        { hostingUrl: `https://www.airbnb.com/rooms/${SMALL_ID}`, startDate: FUTURE, nights: 1, status: 'accepted' },
      ]),
    ]);
    expect(listings[0].reservations).toEqual([]);
  });

  it('ne crée pas de logement à partir d\'un séjour orphelin', () => {
    const { listings } = parseExportDocuments([
      listingsDoc([rawListing()]),
      reservationsDoc([
        { confirmationCode: 'ORPH', hostingUrl: 'https://www.airbnb.com/rooms/99998888', startDate: FUTURE, nights: 1, status: 'accepted' },
      ]),
    ]);
    expect(listings).toHaveLength(1);
    expect(listings[0].external_listing_id).toBe(SMALL_ID);
  });
});

