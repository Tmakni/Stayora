/**
 * Les sources SECONDAIRES de l'export, et la règle qui les gouverne.
 *
 * POURQUOI UN FICHIER À PART
 * --------------------------
 * `airbnbExport.test.js` vérifie la lecture des annonces. Celui-ci vérifie ce
 * qui est venu ensuite : les avis, les séjours, les modèles de message écrits
 * par l'hôte, la traçabilité des champs et l'arbitrage des désaccords entre
 * fichiers.
 *
 * Ces sources sont les plus risquées de l'export : ce sont celles où il serait
 * facile de fabriquer une caractéristique qui n'existe pas. La plupart des
 * tests ci-dessous vérifient donc qu'une donnée N'EST PAS écrite — un champ
 * vide est le résultat attendu, pas un échec.
 */

const { parseExportDocuments } = require('../services/airbnbExport');

const SMALL_ID = '39244203';
const BIG_ID = '1684090983577235984';

function listingsDoc(listings) {
  return { name: 'listings.json', data: [{ listings }] };
}

function rawListing(overrides = {}) {
  return {
    id: Number(SMALL_ID),
    nickname: null,
    propertyType: 'House',
    bedrooms: 2,
    beds: 3,
    bathrooms: 1,
    personCapacity: 5,
    city: 'Parempuyre',
    country: 'FR',
    zipcode: '33290',
    street: '12 Rue des Ardillères',
    formattedAddress: '12 Rue des Ardillères, 33290 Parempuyre, France',
    amenities: ['wireless_internet', 'kitchen'],
    listingDescriptions: [{ name: 'Studio CHIC et cosy', description: 'Une description.' }],
    ...overrides,
  };
}

function reservationsDoc(rows) {
  return { name: 'reservations.json', data: [{ reservations: rows }] };
}

function quickRepliesDoc(templates) {
  return { name: 'host_quick_replies.json', data: [{ templates }] };
}

const FUTURE = new Date(Date.now() + 90 * 86400000).toISOString().slice(0, 10);
const PAST = '2019-05-01';

// ────────────────────────────────────────────────────────────────────────────
describe('reviews.json — note moyenne et nombre d\'avis', () => {
  const reviewsDoc = {
    name: 'reviews.json',
    data: [{
      reviewsReceived: [
        // Comptés : avis reçus par l'hôte sur un logement, réellement soumis.
        { review: { entityType: 'HOME', revieweeRole: 'HOST', hasSubmitted: true, isSystemAutoGenerated: false, entityId: SMALL_ID, rating: 5 } },
        { review: { entityType: 'HOME', revieweeRole: 'HOST', hasSubmitted: true, isSystemAutoGenerated: false, entityId: SMALL_ID, rating: 4 } },
        // Écartés, un par motif — chacun fausserait la note du logement.
        { review: { entityType: 'HOME', revieweeRole: 'GUEST', hasSubmitted: true, isSystemAutoGenerated: false, entityId: SMALL_ID, rating: 1 } },
        { review: { entityType: 'HOME', revieweeRole: 'HOST', hasSubmitted: false, isSystemAutoGenerated: false, entityId: SMALL_ID, rating: 1 } },
        { review: { entityType: 'HOME', revieweeRole: 'HOST', hasSubmitted: true, isSystemAutoGenerated: true, entityId: SMALL_ID, rating: 1 } },
        { review: { entityType: 'HOME', revieweeRole: 'HOST', hasSubmitted: true, isSystemAutoGenerated: false, entityId: SMALL_ID, rating: null } },
      ],
      // Les avis que l'hôte a LAISSÉS à ses voyageurs ne sont pas la note de
      // son logement.
      reviewsProvided: [
        { review: { entityType: 'HOME', revieweeRole: 'GUEST', hasSubmitted: true, isSystemAutoGenerated: false, entityId: SMALL_ID, rating: 1 } },
      ],
    }],
  };

  it('calcule la moyenne sur les seuls avis recevables', () => {
    const [listing] = parseExportDocuments([listingsDoc([rawListing()]), reviewsDoc]).listings;
    expect(listing.review_count).toBe(2);
    expect(listing.rating).toBe(4.5);
    expect(listing.found.reviews).toBe(true);
    expect(listing.import_sources.rating).toBe('reviews.json');
  });

  it('ne pose aucune note quand aucun avis n\'est recevable', () => {
    const empty = {
      name: 'reviews.json',
      data: [{ reviewsReceived: [
        { review: { entityType: 'HOME', revieweeRole: 'GUEST', hasSubmitted: true, entityId: SMALL_ID, rating: 5 } },
      ] }],
    };
    const [listing] = parseExportDocuments([listingsDoc([rawListing()]), empty]).listings;
    expect(listing.rating).toBeUndefined();
    expect(listing.review_count).toBeUndefined();
    expect(listing.found.reviews).toBe(false);
  });
});

