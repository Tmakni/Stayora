describe('host_quick_replies.json — source secondaire sous conditions', () => {
  it('lit l\'heure d\'arrivée d\'un modèle qui ne vise QU\'UN logement', () => {
    const [listing] = parseExportDocuments([
      listingsDoc([rawListing()]),
      quickRepliesDoc([{
        entities: [{ entityType: 'LISTING', entityId: SMALL_ID }],
        texts: [{ message: 'Votre arrivée est possible à partir de 16h.', locale: 'fr' }],
      }]),
    ]).listings;

    expect(listing.check_in_time).toBe('16:00');
    // La provenance doit dire que cette valeur ne vient PAS de l'annonce.
    expect(listing.import_sources.check_in_time).toBe('host_quick_replies.json');
  });

  it('ignore un modèle rattaché à plusieurs logements', () => {
    const [listing] = parseExportDocuments([
      listingsDoc([rawListing()]),
      quickRepliesDoc([{
        entities: [
          { entityType: 'LISTING', entityId: SMALL_ID },
          { entityType: 'LISTING', entityId: BIG_ID },
        ],
        texts: [{ message: 'Arrivée à partir de 16h.', locale: 'fr' }],
      }]),
    ]).listings;
    expect(listing.check_in_time).toBeUndefined();
  });

  it('ignore un espace réservé : sa valeur n\'est pas dans l\'export', () => {
    const [listing] = parseExportDocuments([
      listingsDoc([rawListing()]),
      quickRepliesDoc([{
        entities: [{ entityType: 'LISTING', entityId: SMALL_ID }],
        texts: [{ message: 'Arrivée à partir de #{CHECK_IN_TIME}.', locale: 'fr' }],
      }]),
    ]).listings;
    expect(listing.check_in_time).toBeUndefined();
  });

  it('laisse le champ vide quand deux modèles se contredisent', () => {
    const [listing] = parseExportDocuments([
      listingsDoc([rawListing()]),
      quickRepliesDoc([
        { entities: [{ entityType: 'LISTING', entityId: SMALL_ID }], texts: [{ message: 'à partir de 16h' }] },
        { entities: [{ entityType: 'LISTING', entityId: SMALL_ID }], texts: [{ message: 'à partir de 18h' }] },
      ]),
    ]).listings;
    expect(listing.check_in_time).toBeUndefined();
  });

  it('ne lit rien d\'autre que l\'heure d\'arrivée', () => {
    const [listing] = parseExportDocuments([
      listingsDoc([rawListing()]),
      quickRepliesDoc([{
        entities: [{ entityType: 'LISTING', entityId: SMALL_ID }],
        texts: [{ message: 'Le code de la boîte à clés est 1009. Le wifi est LIVEBOX-4A2B.' }],
      }]),
    ]).listings;
    // Un code et un nom de réseau lus dans un message peuvent être périmés,
    // ou avoir été donnés à un seul voyageur. Ils ne deviennent pas des
    // caractéristiques.
    expect(listing.access_code).toBeUndefined();
    expect(listing.wifi_name).toBeUndefined();
    expect(JSON.stringify(listing)).not.toContain('1009');
  });
});

